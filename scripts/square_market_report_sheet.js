function buildRows(locations, summaries, deposits) {
  locations = selectLocations(locations, summaries, deposits);
  const data = [HEADERS, ...locations.map((location, i) => {
    const summary = summaries[location.name] || { locationName: location.name, cash: 0, cash_refunds: 0 };
    const reported = reconcileLocationDeposits(summary, deposits);
    const workers = [...new Set(deposits.filter(entry => entry.market === marketKey(location.name))
      .flatMap(entry => entry.workers || []))];
    const row = i + 2;
    return [location.name, workers.join(', '), (summary.cash - summary.cash_refunds) / 100,
      reported.actualCash === null ? 'MISSING' : reported.actualCash / 100,
      reported.actualTokens === null ? 'MISSING' : reported.actualTokens / 100,
      null, null, { formulaValue: `=IF(COUNT(F${row}:G${row})=0,"",SUM(F${row}:G${row}))` },
      { formulaValue: `=IF(H${row}="","",H${row}-C${row})` }, null];
  })];
  const end = locations.length + 1;
  data.push(...Array.from({ length: 3 }, () => Array(10).fill(null)));
  data.push(['TOTAL', null, ...'CDEFGHI'.split('').map(column => ({ formulaValue: `=SUM(${column}2:${column}${end})` })), null]);
  return data.map(row => ({ values: row.map(value => value === null ? {} : {
    userEnteredValue: typeof value === 'object' ? value : typeof value === 'number'
      ? { numberValue: value } : { stringValue: value },
  }) }));
}

async function updateReconciliationSheet({ start, end, locations, summaries, deposits, dryRun = false, client }) {
  const baseTitle = `square-auto-${DateTime.fromISO(start).toFormat('M/d')}-${DateTime.fromISO(end).toFormat('M/d')}`;
  if (dryRun) return `DRY RUN: would create a new ${baseTitle} tab (using a numbered suffix if needed); no spreadsheet changes made.`;
  client ||= await buildGoogleSheetsClient(true);
  const id = process.env.SQUARE_REPORT_SPREADSHEET_ID || WORKBOOK_ID;
  const { data: metadata } = await client.get(`/${id}`, { params: { fields: 'sheets.properties' } });
  const title = nextTitle(baseTitle, metadata.sheets || []);
  const period = `${start} to ${end}`;
  const sheetId = Math.floor(Math.random() * 2000000000);
  const rows = buildRows(locations, summaries, deposits);
  rows[0].values[0].note = period;
  const height = Math.max(rows.length, 2);
  const range = (r0, r1, c0, c1) => ({ sheetId, startRowIndex: r0, endRowIndex: r1, startColumnIndex: c0, endColumnIndex: c1 });
  const requests = [];
  requests.push({ addSheet: { properties: { sheetId, title, index: 0,
    gridProperties: { rowCount: Math.max(100, height), columnCount: 10, frozenRowCount: 1 } } } });
  requests.push(
    { updateCells: { range: range(0, rows.length, 0, 10), rows, fields: 'userEnteredValue,note' } },
    { repeatCell: { range: range(0, height, 0, 10), cell: { userEnteredFormat: { wrapStrategy: 'WRAP', textFormat: { fontFamily: 'Arial', fontSize: 11 } } }, fields: 'userEnteredFormat(wrapStrategy,textFormat)' } },
    { repeatCell: { range: range(0, 1, 0, 10), cell: { userEnteredFormat: { backgroundColor: { red: .93, green: .93, blue: .93 }, textFormat: { bold: true } } }, fields: 'userEnteredFormat(backgroundColor,textFormat.bold)' } },
    { repeatCell: { range: range(1, height, 2, 9), cell: { userEnteredFormat: { numberFormat: { type: 'CURRENCY', pattern: '$#,##0.00;-$#,##0.00' } } }, fields: 'userEnteredFormat.numberFormat' } },
    { repeatCell: { range: range(1, rows.length - 4, 5, 7), cell: { userEnteredFormat: { backgroundColor: { red: 1, green: .95, blue: .8 } } }, fields: 'userEnteredFormat.backgroundColor' } },
    { updateDimensionProperties: { range: { sheetId, dimension: 'COLUMNS', startIndex: 0, endIndex: 10 }, properties: { pixelSize: 140 }, fields: 'pixelSize' } },
    { updateDimensionProperties: { range: { sheetId, dimension: 'COLUMNS', startIndex: 9, endIndex: 10 }, properties: { pixelSize: 280 }, fields: 'pixelSize' } },
    { updateDimensionProperties: { range: { sheetId, dimension: 'ROWS', startIndex: 0, endIndex: 1 }, properties: { pixelSize: 55 }, fields: 'pixelSize' } },
  );
  const totalRange = range(rows.length - 1, rows.length, 2, 9);
  const border = { style: 'SOLID', color: { red: 0, green: 0, blue: 0 } };
  requests.push(
    { repeatCell: { range: range(rows.length - 1, rows.length, 0, 9), cell: { userEnteredFormat: { textFormat: { bold: true } } }, fields: 'userEnteredFormat.textFormat.bold' } },
    { updateBorders: { range: totalRange, top: border, bottom: border, left: border, right: border, innerVertical: border } },
  );
  const instructions = (metadata.sheets || []).find(sheet => sheet.properties.title === 'Instructions');
  if (instructions) {
    requests.push({ updateSheetProperties: { properties: { sheetId: instructions.properties.sheetId, index: 0 }, fields: 'index' } });
  } else {
    const usedIds = new Set([sheetId, ...(metadata.sheets || []).map(sheet => sheet.properties.sheetId)]);
    let instructionId = sheetId + 1;
    while (usedIds.has(instructionId)) instructionId++;
    requests.push(...instructionRequests(instructionId));
  }
  await client.post(`/${id}:batchUpdate`, { requests });
  return `CREATED ${title}: https://docs.google.com/spreadsheets/d/${id}/edit#gid=${sheetId}`;
}

module.exports = { updateReconciliationSheet, buildRows, selectLocations, nextTitle, HEADERS };
