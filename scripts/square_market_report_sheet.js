const { DateTime } = require('luxon');
const { buildGoogleSheetsClient } = require('./market_feedback_report');
const { marketKey, reconcileLocationDeposits } = require('./square_market_report_deposits');

const WORKBOOK_ID = '14o6GY4MERLpdIHdrsZW2XAvRkT_9Ydv-csyz1QEYvrE';
const HEADERS = ['Market', 'Rep', 'Square Cash/Token', 'Rep Cash', 'Rep Tokens',
  'Actual Cash', 'Actual Token', 'Actual Cash/Token', 'Difference Actual - Square', 'Notes'];
const ALWAYS_MARKETS = ['Hillsdale', 'Hollywood', 'King', 'LCFM', 'Montavilla', 'PSU', 'Springfield', 'Woodstock'];

function selectLocations(locations, summaries, deposits) {
  const required = new Set(ALWAYS_MARKETS.map(marketKey));
  const selected = locations.filter(location => required.has(marketKey(location.name))
    || summaries[location.name]?.orderCount > 0
    || Object.values(summaries[location.name] || {}).some(value => typeof value === 'number' && value !== 0)
    || deposits.some(entry => entry.market === marketKey(location.name)));
  for (const name of ALWAYS_MARKETS) {
    if (!selected.some(location => marketKey(location.name) === marketKey(name))) selected.push({ name });
  }
  return selected;
}

function nextTitle(base, sheets) {
  const names = new Set(sheets.map(sheet => sheet.properties.title));
  let title = base;
  for (let suffix = 1; names.has(title); suffix++) title = `${base}.${suffix}`;
  return title;
}

